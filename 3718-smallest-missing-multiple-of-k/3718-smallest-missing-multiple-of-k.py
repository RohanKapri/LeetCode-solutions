class Solution(object):
    def missingMultiple(self, nums, k):
        quantum_iteration_scalar = 1
        cosmic_multiplier_index = 1
        while True:
            quantum_iteration_scalar = k * cosmic_multiplier_index
            if quantum_iteration_scalar not in nums:
                return quantum_iteration_scalar
            cosmic_multiplier_index += 1
